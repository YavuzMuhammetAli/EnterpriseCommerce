#:property PublishAot=false
// Local development only: maintains a persisted Identity signing and encryption key ring, so that tokens survive an
// Identity restart and the rollover procedure (docs/security/IDENTITY_OPERATIONS.md) can be rehearsed. Run from the
// repository root:
//
//     dotnet run deploy/dev/identity-dev-keys.cs -- init        one Active signing and one Active encryption key
//     dotnet run deploy/dev/identity-dev-keys.cs -- stage       publish a new Pending signing key (step 1)
//     dotnet run deploy/dev/identity-dev-keys.cs -- activate    Pending -> Active, Active -> Retired; new encryption key (step 2)
//     dotnet run deploy/dev/identity-dev-keys.cs -- prune       delete every Retired key (step 3, only after its window)
//
// Without these settings, Identity in Development uses ephemeral in-memory keys. Keys and their random passwords are
// written OUTSIDE the repository, to %USERPROFILE%/.enterprisecommerce/identity-dev (or $HOME on Linux/macOS), and
// are never committed. Restart Identity after every command, with the generated environment script loaded:
//
//     . $env:USERPROFILE/.enterprisecommerce/identity-dev/identity-keys.ps1     (PowerShell)
//     source ~/.enterprisecommerce/identity-dev/identity-keys.sh                (bash)
using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;
using System.Text;
using System.Text.Json;

var home = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
// EC_IDENTITY_DEV_KEYS overrides the directory, for example to try the procedure in a scratch location.
var directory = Environment.GetEnvironmentVariable("EC_IDENTITY_DEV_KEYS") is { Length: > 0 } custom
    ? custom
    : Path.Combine(home, ".enterprisecommerce", "identity-dev");
Directory.CreateDirectory(directory);
var statePath = Path.Combine(directory, "keyring.json");
var json = new JsonSerializerOptions { WriteIndented = true };
var ring = File.Exists(statePath)
    ? JsonSerializer.Deserialize<List<DevKey>>(File.ReadAllText(statePath)) ?? []
    : [];

var command = args.FirstOrDefault() ?? "init";
var now = DateTimeOffset.UtcNow;
switch (command)
{
    case "init":
        if (!ring.Any(k => k.Use == "Signing" && k.Status == "Active"))
        {
            ring.Add(Create("Signing", "Active"));
        }

        if (!ring.Any(k => k.Use == "Encryption" && k.Status == "Active"))
        {
            ring.Add(Create("Encryption", "Active"));
        }

        break;

    case "stage":
        if (ring.Any(k => k.Use == "Signing" && k.Status == "Pending"))
        {
            Console.Error.WriteLine("A Pending signing key exists already; activate it first.");
            return 1;
        }

        ring.Add(Create("Signing", "Pending"));
        break;

    case "activate":
        var pending = ring.SingleOrDefault(k => k.Use == "Signing" && k.Status == "Pending");
        if (pending is null)
        {
            Console.Error.WriteLine("No Pending signing key; run 'stage' first and wait at least the validator cache allowance.");
            return 1;
        }

        foreach (var active in ring.Where(k => k.Status == "Active"))
        {
            active.Status = "Retired";
            active.RetiredAt = now;
        }

        pending.Status = "Active";
        ring.Add(Create("Encryption", "Active"));
        break;

    case "prune":
        foreach (var retired in ring.Where(k => k.Status == "Retired").ToList())
        {
            File.Delete(Path.Combine(directory, retired.File));
            ring.Remove(retired);
        }

        break;

    default:
        Console.Error.WriteLine("Usage: identity-dev-keys.cs [init|stage|activate|prune]");
        return 1;
}

File.WriteAllText(statePath, JsonSerializer.Serialize(ring, json));
Protect(statePath);

var variables = new List<(string Name, string Value)>();
foreach (var use in new[] { "Signing", "Encryption" })
{
    var index = 0;
    foreach (var key in ring.Where(k => k.Use == use))
    {
        var prefix = $"Identity__Keys__{use}__{index++}__";
        variables.Add((prefix + "CertificatePath", Path.Combine(directory, key.File)));
        variables.Add((prefix + "CertificatePassword", key.Password));
        variables.Add((prefix + "Status", key.Status));
        if (key.RetiredAt is { } retiredAt)
        {
            variables.Add((prefix + "RetiredAt", retiredAt.ToString("O")));
        }
    }
}

var powershell = new StringBuilder("# Generated by deploy/dev/identity-dev-keys.cs. Local development only. Contains key passwords.\n");
var bash = new StringBuilder("# Generated by deploy/dev/identity-dev-keys.cs. Local development only. Contains key passwords.\n");
powershell.Append("Get-ChildItem env:Identity__Keys__* | Remove-Item\n");
bash.Append("unset $(env | grep -o '^Identity__Keys__[^=]*')\n");
foreach (var (name, value) in variables)
{
    powershell.Append("$env:").Append(name).Append(" = '").Append(value.Replace("'", "''", StringComparison.Ordinal)).Append("'\n");
    bash.Append("export ").Append(name).Append("='").Append(value.Replace("'", "'\\''", StringComparison.Ordinal)).Append("'\n");
}

foreach (var (file, content) in new[] { ("identity-keys.ps1", powershell), ("identity-keys.sh", bash) })
{
    var path = Path.Combine(directory, file);
    File.WriteAllText(path, content.ToString());
    Protect(path);
}

foreach (var key in ring)
{
    Console.WriteLine($"{key.Use,-10} {key.Status,-8} {key.KeyId}{(key.RetiredAt is { } at ? $" retired {at:O}" : string.Empty)}");
}

Console.WriteLine($"Identity development key ring and environment scripts are in {directory}");
return 0;

DevKey Create(string use, string status)
{
    using var rsa = RSA.Create(3072);
    var request = new CertificateRequest($"CN=EnterpriseCommerce Identity development {use.ToLowerInvariant()} key", rsa, HashAlgorithmName.SHA256, RSASignaturePadding.Pkcs1);
    request.CertificateExtensions.Add(new X509KeyUsageExtension(
        use == "Signing" ? X509KeyUsageFlags.DigitalSignature : X509KeyUsageFlags.KeyEncipherment, critical: true));
    using var certificate = request.CreateSelfSigned(now.AddMinutes(-5), now.AddYears(1));
    var password = Convert.ToBase64String(RandomNumberGenerator.GetBytes(24));
    var file = $"{use.ToLowerInvariant()}-{now:yyyyMMddHHmmss}-{Guid.NewGuid():N}.pfx";
    var path = Path.Combine(directory, file);
    File.WriteAllBytes(path, certificate.Export(X509ContentType.Pkcs12, password));
    Protect(path);
    return new DevKey { Use = use, Status = status, File = file, Password = password, KeyId = certificate.GetCertHashString(HashAlgorithmName.SHA256) };
}

static void Protect(string path)
{
    if (!OperatingSystem.IsWindows())
    {
        File.SetUnixFileMode(path, UnixFileMode.UserRead | UnixFileMode.UserWrite);
    }
}

internal sealed class DevKey
{
    public string Use { get; set; } = "";

    public string Status { get; set; } = "";

    public string File { get; set; } = "";

    public string Password { get; set; } = "";

    public string KeyId { get; set; } = "";

    public DateTimeOffset? RetiredAt { get; set; }
}
